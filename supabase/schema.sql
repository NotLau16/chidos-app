-- 1. Tabla de pedidos (orders)
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  status text not null default 'new' check (status in ('new', 'preparing', 'ready', 'delivered', 'cancelled')),
  mode text not null check (mode in ('delivery', 'takeaway')),
  source text not null default 'web' check (source in ('web', 'manual')),
  customer jsonb not null,
  address jsonb,
  items jsonb not null,
  subtotal numeric not null,
  delivery_fee numeric not null default 0,
  total numeric not null,
  payment jsonb not null
);

-- Habilitar replicación Realtime en la tabla orders
alter publication supabase_realtime add table public.orders;

-- 2. Políticas de Seguridad (RLS)
alter table public.orders enable row level security;

-- Permitir a clientes crear pedidos desde la tienda web
create policy "Permitir inserción de pedidos a anon/public"
  on public.orders for insert
  with check (true);

-- Permitir lectura para la demo y administración
create policy "Permitir lectura de pedidos"
  on public.orders for select
  using (true);

-- Permitir actualización de estados desde admin
create policy "Permitir actualización de pedidos"
  on public.orders for update
  using (true);

-- 3. Tabla de configuración (opcional)
create table if not exists public.settings (
  id text primary key default 'main',
  is_open boolean not null default true,
  transfer_alias text not null default 'chidos.salta.mp',
  delivery_eta text not null default '35-45 min',
  takeaway_eta text not null default '20-25 min',
  address text not null default 'Vía Aurelia, Manzana 44, Lote 05 - Zona Sur, Salta Capital',
  whatsapp text not null default '5493873139696',
  instagram text not null default 'chidos.ok',
  zones jsonb not null default '[]'::jsonb,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.settings enable row level security;
create policy "Lectura pública de settings" on public.settings for select using (true);
create policy "Actualización de settings" on public.settings for all using (true);
